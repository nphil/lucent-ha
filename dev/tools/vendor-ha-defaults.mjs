/** Refreshes dev/fixtures/ha-defaults.json: Home Assistant's own default theme variables, read from the frontend source.
 *
 *   node dev/tools/vendor-ha-defaults.mjs [git-ref]        (default ref: the tag below; needs internet)
 *
 * What it keeps (the same split Home Assistant's `applyThemesOnElement` uses, src/common/dom/apply_themes_on_element.ts):
 *   lightCss    every `html { --var: value }` default block, as plain CSS (the page stylesheet Home Assistant ships)
 *   darkVars    the variables Home Assistant sets inline on <html> when dark mode is on, before the theme's own
 *   derivedVars the defaults that point at other variables with var(...): re-applied inline with every custom theme
 * The harness (dev/ha-theme.ts) replays them in that order, so a theme switch behaves like the real thing. */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REF = process.argv[2] ?? "20260826.7";
const RAW = `https://raw.githubusercontent.com/home-assistant/frontend/${REF}/src/resources/theme`;
const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "fixtures", "ha-defaults.json");

/** Every exported `css` block of a Home Assistant style file, by export name (template placeholders dropped). */
async function cssBlocks(path) {
  const response = await fetch(`${RAW}/${path}`);
  if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
  const source = await response.text();
  const blocks = {};
  for (const match of source.matchAll(/export const (\w+) = css`([\s\S]*?)`;/g)) blocks[match[1]] = match[2].replace(/\$\{[^}]*\}/g, "");
  return blocks;
}

/** Home Assistant's `_extractCssVars`: split on ";", keep the chunks that declare a --variable. */
function extractVars(css, condition = () => true) {
  const variables = {};
  for (const rawLine of css.split(";")) {
    const line = rawLine.substring(rawLine.indexOf("--")).trim();
    if (line.startsWith("--") && condition(line)) {
      const [name, value] = line.split(":").map((part) => part.replaceAll("}", "").trim());
      variables[name.substring(2)] = value;
    }
  }
  return variables;
}

/** Home Assistant's `extractDerivedVars`: only the declarations that use var(...). */
const extractDerivedVars = (css) => (css.includes("var(") ? extractVars(css, (line) => line.includes("var(")) : {});

const [core, main, typography, semantic, animations, wa, colorCore, colorSemantic, color, colorWa] = await Promise.all([
  cssBlocks("core.globals.ts"),
  cssBlocks("main.globals.ts"),
  cssBlocks("typography.globals.ts"),
  cssBlocks("semantic.globals.ts"),
  cssBlocks("animations.globals.ts"),
  cssBlocks("wa.globals.ts"),
  cssBlocks("color/core.globals.ts"),
  cssBlocks("color/semantic.globals.ts"),
  cssBlocks("color/color.globals.ts"),
  cssBlocks("color/wa.globals.ts"),
]);

// theme.ts: themeStyles = core, main, typography, semantic, color (core, semantic, color, wa), fonts, wa, animations.
const light = [
  core.coreStyles, main.mainStyles, typography.typographyStyles, semantic.semanticStyles,
  colorCore.coreColorStyles, colorSemantic.semanticColorStyles, color.colorStyles, colorWa.waColorStyles,
  wa.waMainStyles, animations.animationStyles,
];
const derived = {
  ...extractDerivedVars(core.coreStyles),
  ...extractDerivedVars(main.mainStyles),
  ...extractDerivedVars(typography.typographyStyles),
  ...extractDerivedVars(color.colorStyles),
  ...extractDerivedVars(colorSemantic.semanticColorStyles),
  ...extractDerivedVars(colorWa.waColorStyles),
  ...extractDerivedVars(wa.waMainStyles),
};
const dark = { ...extractVars(semantic.darkSemanticStyles), ...extractVars(color.darkColorStyles), ...extractVars(colorSemantic.darkSemanticColorStyles) };

const data = {
  source: { repo: "https://github.com/home-assistant/frontend", ref: REF, path: "src/resources/theme", note: "generated by dev/tools/vendor-ha-defaults.mjs, do not edit" },
  lightCss: light.map((block) => block.replace(/\n\s*\n/g, "\n").trim()).join("\n"),
  darkVars: dark,
  derivedVars: derived,
};
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, `${JSON.stringify(data, null, 1)}\n`);
console.log(`ha-defaults.json from ${REF}: ${data.lightCss.length} chars of default CSS, ${Object.keys(dark).length} dark variables, ${Object.keys(derived).length} derived variables`);
